// CLU's home on the PC (M2): the core brain as a background process with a local, token-protected API.
// No new frameworks: the JDK's built-in HTTP server, SQLite through JDBC, and Gradle's standard application plugin.
plugins {
    kotlin("jvm")
    kotlin("plugin.serialization")
    application
}

kotlin {
    jvmToolchain(21)
    compilerOptions { jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17) }
}
java {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
}

dependencies {
    implementation(project(":core"))
    implementation("org.xerial:sqlite-jdbc:3.47.1.0")
    // LiveKit's FFI protocol (classes generated by scripts/build_voice_native.sh into src/ffi/java).
    implementation("com.google.protobuf:protobuf-javalite:4.36.2")
    // Voice downloads are .tar.bz2 archives (sherpa-onnx releases).
    implementation("org.apache.commons:commons-compress:1.27.1")
    testImplementation(kotlin("test"))
    testImplementation("org.junit.jupiter:junit-jupiter:5.11.4")
    testRuntimeOnly("org.junit.platform:junit-platform-launcher")
}

sourceSets { main { java.srcDir("src/ffi/java") } }

application {
    mainClass.set("ai.clu.desktop.HostMainKt")
    applicationName = "clu-host"
    // A small, steady footprint: the model lives in native memory (llama.cpp), not on the Java heap.
    applicationDefaultJvmArgs = listOf("-Xmx384m", "-XX:+UseSerialGC", "-XX:MaxMetaspaceSize=160m", "-Xss1m")
}

// Native libraries next to the jars: lib/native/<os>-x64/. The Windows DLL comes from native/build/cmake-windows
// (cross-built with native/windows-x64.toolchain.cmake); the Linux one from the host build.
distributions {
    main {
        contents {
            from(rootProject.file("native/build/host/libclu_llama.so")) { into("lib/native/linux-x64") }
            from(rootProject.file("native/build/cmake-windows/clu_llama.dll")) { into("lib/native/windows-x64") }
            // Optional GPU (Vulkan) build of the engine, only if it was built (scripts/build_windows_native.sh --vulkan).
            from(rootProject.file("native/build/cmake-windows-vulkan/clu_llama.dll")) { into("lib/native/windows-x64-vulkan") }
        }
    }
}

tasks.test {
    useJUnitPlatform()
    maxHeapSize = "1g"
    testLogging { events("failed"); exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL }
    systemProperty("clu.nativeLib", rootProject.file("native/build/host/libclu_llama.so").absolutePath)
    systemProperty("clu.testModel", rootProject.file("native/build/test/tiny.gguf").absolutePath)
    // Opt-in: a real GGUF for the end-to-end host test (HostRealModelTest); Node + Playwright for the window test (ShellUiTest).
    listOf("clu.desktopRealModel", "clu.shellUi", "clu.shellUiShots", "clu.voiceDebug", "clu.voiceRealModel", "clu.voiceMeasureOut").forEach { k -> System.getProperty(k)?.let { systemProperty(k, it) } }
}
